import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Native chrome uses the React app's tokens. Keep the generated Swift checked
// in so plain `swift build` works; the bundle build checks it for drift.
const root = new URL('../../', import.meta.url);
const base = readFileSync(new URL('web/src/styles/tokens.css', root), 'utf8');
const themes = readFileSync(new URL('web/src/themes.css', root), 'utf8');
const declarations = (text) => Object.fromEntries(
  [...text.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]),
);
const block = (text, selector) => {
  const start = text.indexOf(selector);
  if (start < 0) throw new Error(`Missing theme: ${selector}`);
  return text.slice(text.indexOf('{', start) + 1, text.indexOf('}', start));
};
const defaults = declarations(block(base, ':root {'));
const light = { ...defaults, ...declarations(block(base, '[data-theme="light"]')) };
const dark = { ...defaults, ...declarations(block(themes, ':root[data-theme="galaxy"]')) };
const colors = ['panel', 'panel-2', 'panel-raised', 'input-bg', 'fill', 'fill-strong', 'row-hover', 'row-selected',
  'line', 'line-strong', 'line-hover', 'text', 'text-strong', 'text-2', 'text-3', 'text-4', 'accent', 'on-accent',
  'focus', 'selection', 'red-text'];
const metrics = ['radius-md', 'radius-lg', 'control-sm', 'control-md', 'fs-sm', 'fs-xs'];
const color = (value) => {
  if (!/^#[0-9a-f]{6}(?:[0-9a-f]{2})?$/i.test(value)) throw new Error(`Unsupported native color: ${value}`);
  // Normalize to RGBA, including selection's alpha.
  return `0x${value.slice(1)}${value.length === 7 ? 'ff' : ''}`;
};
const number = (value) => {
  if (!/^\d+(?:\.\d+)?px$/.test(value)) throw new Error(`Unsupported native metric: ${value}`);
  return value.slice(0, -2);
};
const output = `// Generated by node native/scripts/theme.mjs from the React theme tokens.\n// Do not edit by hand. Dark is Galaxy; light is Light (see web/src/theme.ts).\nimport AppKit\n\nenum NativeTheme {\n    static let colors: [String: (dark: UInt32, light: UInt32)] = [\n${colors.map((key) => `        "${key}": (${color(dark[key])}, ${color(light[key])}),`).join('\n')}\n    ]\n    static let metrics: [String: (dark: CGFloat, light: CGFloat)] = [\n${metrics.map((key) => `        "${key}": (${number(dark[key])}, ${number(light[key])}),`).join('\n')}\n    ]\n}\n`;
const file = new URL('native/Sources/PaseoCommandNative/NativeTheme.swift', root);
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== output) throw new Error('Native theme is stale. Run node native/scripts/theme.mjs');
} else {
  writeFileSync(file, output);
}
console.log(`Native theme ${process.argv.includes('--check') ? 'matches React' : 'generated'} (${fileURLToPath(file)})`);
