/** Skin tones as Slack names them (`::skin-tone-2:` … `::skin-tone-6:`): their modifiers. */
export const SKIN_TONES: Record<number, string> = {
  2: "\u{1F3FB}",
  3: "\u{1F3FC}",
  4: "\u{1F3FD}",
  5: "\u{1F3FE}",
  6: "\u{1F3FF}",
};

/** Slack's code points ("1f44d-1f3fb") as the emoji; undefined for anything malformed. */
export function fromCodePoints(unicode: string | undefined): string | undefined {
  if (!unicode || !/^[0-9a-f]{2,6}(-[0-9a-f]{2,6})*$/i.test(unicode)) return undefined;
  try {
    return String.fromCodePoint(...unicode.split("-").map((h) => parseInt(h, 16)));
  } catch {
    return undefined;
  }
}

/** A standard emoji with a skin tone, when it takes one (the tone goes after its first character). */
export function withSkinTone(emoji: string, tone: number | undefined): string {
  const modifier = tone ? SKIN_TONES[tone] : undefined;
  if (!modifier) return emoji;
  const [first, ...rest] = [...emoji.replace(/️/g, "")];
  return `${first}${modifier}${rest.join("")}`;
}

/** What an emoji name stands for: a standard emoji, a custom emoji's name (aliases followed), or nothing known. */
export type EmojiFace = { kind: "unicode"; char: string } | { kind: "custom"; name: string } | { kind: "unknown" };

/** An emoji name as the workspace knows it: custom emoji first (as Slack resolves them), following aliases, then standard ones. */
export function emojiFace(name: string, custom: Record<string, string> = {}): EmojiFace {
  let current = name;
  for (let hops = 0; hops < 5; hops++) {
    const value = custom[current];
    if (value === undefined) break;
    if (!value.startsWith("alias:")) return { kind: "custom", name: current };
    current = value.slice("alias:".length);
  }
  const char = EMOJI[current];
  return char ? { kind: "unicode", char } : { kind: "unknown" };
}

/** Emoji names starting with (then containing) `query`, custom ones too, for the composer's `:` autocomplete. */
export function matchEmoji(query: string, custom: Record<string, string> = {}, limit = 8): string[] {
  const q = query.toLowerCase();
  const names = [...new Set([...Object.keys(custom), ...Object.keys(EMOJI)])];
  const starts = names.filter((n) => n.startsWith(q));
  const contains = q.length >= 2 ? names.filter((n) => !n.startsWith(q) && n.includes(q)) : [];
  const byLength = (a: string, b: string) => a.length - b.length || a.localeCompare(b);
  return [...starts.sort(byLength), ...contains.sort(byLength)].slice(0, limit);
}
